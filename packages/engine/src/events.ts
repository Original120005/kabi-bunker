const UNDO_LIMIT = 10;

/** When the event reel should write its card, or null if nothing is waiting. */
export function pendingEventAt(state: RoomState): number | null {
  const spin = state.event?.spin;
  if (!spin || spin.applied || state.status !== "playing" || !state.game) return null;
  return spin.at + RAID.pickSpinMs;
}

/** Writes the spun health line or backpack item. The card can be undone; the announcement stays. */
export function settleEvent(state: RoomState, prev: RoomState, newId: () => string, now: number) {
  const spin = state.event?.spin;
  const game = state.game;
  if (!spin || spin.applied || !game) return;
  spin.applied = true;
  const playerId = spin.winnerId;
  const name = state.participants.find((p) => p.id === playerId)?.nickname ?? "Игрок";
  if (!game.seatOrder.includes(playerId) || !game.hands[playerId]) {
    state.log.push({ at: now, text: `Ивент «${state.event!.title}»: ${name} уже не в игре, карта не записана` });
    return;
  }

  const key = spin.effect.kind === "health" ? "health" : "backpack";
  const def = game.characteristics.find((c) => c.key === key);
  if (!def) return;
  const modifiers: Record<string, string> = spin.effect.kind === "health" ? { severity: spin.effect.severity } : {};
  const card = makeCard(def, null, playerId, modifiers, newId());
  card.title = spin.effect.title;
  card.description = spin.effect.description;
  if (spin.effect.kind === "health" && spin.effect.link) card.link = spin.effect.link;
  card.revealed = true;
  game.cards[card.id] = card;

  const hand = game.hands[playerId][key] ?? [];
  if (key === "backpack") {
    const existing = hand.map((id) => game.cards[id]).filter((c) => c && (c.contentId || c.title !== "Пусто"));
    for (const id of hand) if (!existing.some((c) => c.id === id)) delete game.cards[id];
    game.hands[playerId][key] = [...existing, card].map((c) => c.id);
  } else {
    game.hands[playerId][key] = [...hand, card.id];
  }

  const label = spin.effect.kind === "health" ? `${name}: ${spin.effect.title} в здоровье` : `${name} получает «${spin.effect.title}»`;
  state.log.push({ at: now, text: `Ивент «${state.event!.title}»: ${label}` });
  if (prev.game) {
    const revealedAfter = Object.values(game.cards).filter((c) => c.revealed).map((c) => c.id);
    state.undo.push({ label: `Ивент «${state.event!.title}»: ${label}`, game: prev.game, rngState: prev.rngState, revealedAfter });
    if (state.undo.length > UNDO_LIMIT) state.undo.shift();
  }
}
